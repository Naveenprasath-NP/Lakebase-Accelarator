"""Deployment — Node 8.

Writes flat bundle to Databricks Workspace (/Workspace/Shared/),
creates app, waits for ACTIVE, deploys code, checks logs for success.
Returns URL only when app is confirmed running.

If deployment fails, captures error logs and sets deployment_error_logs
in state so the pipeline can route back to backend_dev for self-healing.
"""

import base64
import time

import httpx

from lakebase_accelerator.agent.state import PipelineState
from lakebase_accelerator.agent.tools import _get_repo
from lakebase_accelerator.settings import get_settings
from lakebase_accelerator.utils.logger import logger

WORKSPACE_BASE = "/Workspace/Shared/lakebase-accelerator-apps"
LOCAL_OUTPUT_DIR = "generated_apps"
MAX_DEPLOYMENT_RETRIES = 2


def deployment_node(state: PipelineState) -> dict:
    """Full deployment: write files → create app → deploy → check logs → return URL.

    On failure, captures error logs into state for self-healing retry.
    """
    logger.info("Node: deployment — starting", extra={"step": "deployment"})

    settings = get_settings()
    bundle_files = state.get("bundle_files", {})
    app_name = state["app_name"]
    schema_name = state["schema_name"]
    retry_count = state.get("deployment_retry_count", 0)

    if not bundle_files:
        return {"error": "No bundle files to deploy", "current_step": "deployment"}

    token = _get_token(settings)
    headers = {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}

    # ─── Step 0: Write locally for inspection ────────────────────────
    _write_locally(app_name, bundle_files)

    # ─── Step 1: Clean workspace path (remove stale notebooks/files) ─
    workspace_path = f"{WORKSPACE_BASE}/{app_name}"
    logger.info(f"Cleaning workspace path: {workspace_path}", extra={"step": "deployment"})
    _clean_workspace(settings.databricks_host, token, workspace_path)

    # ─── Step 2: Write to Databricks Workspace (plain files, NOT notebooks)
    logger.info(f"Writing {len(bundle_files)} files to {workspace_path}", extra={"step": "deployment"})

    success_count = 0
    for file_path, content in bundle_files.items():
        full_path = f"{workspace_path}/{file_path}"
        if _write_file(settings.databricks_host, token, full_path, content):
            success_count += 1

    logger.info(f"Wrote {success_count}/{len(bundle_files)} files", extra={"step": "deployment"})

    if success_count == 0:
        return {"error": "Failed to write files to workspace", "current_step": "deployment"}

    # ─── Step 3: Create App ──────────────────────────────────────────
    logger.info(f"Creating app: {app_name}", extra={"step": "deployment"})

    # Check if app already exists
    check_resp = httpx.get(
        f"{settings.databricks_host}/api/2.0/apps/{app_name}",
        headers=headers,
        timeout=15.0,
    )

    if check_resp.status_code == 200:
        app_data = check_resp.json()
        logger.info(f"App already exists: {app_name}", extra={"step": "deployment"})
    else:
        create_resp = httpx.post(
            f"{settings.databricks_host}/api/2.0/apps",
            json={"name": app_name, "description": "Generated by Lakebase Accelerator"},
            headers=headers,
            timeout=30.0,
        )

        if create_resp.status_code not in (200, 201):
            return {"error": f"App creation failed: {create_resp.text[:200]}", "current_step": "deployment"}

        app_data = create_resp.json()

    app_url = app_data.get("url", "")
    sp_client_id = app_data.get("service_principal_client_id", "")

    logger.info(f"App ready: {app_name}, SP: {sp_client_id}", extra={"step": "deployment"})

    # ─── Step 4: Wait for ACTIVE ─────────────────────────────────────
    logger.info("Waiting for app compute to be ACTIVE...", extra={"step": "deployment"})
    if not _wait_for_active(settings.databricks_host, token, app_name, timeout=300):
        return {"error": "App did not reach ACTIVE state", "current_step": "deployment"}

    # ─── Step 5: Deploy code ─────────────────────────────────────────
    logger.info("Deploying code...", extra={"step": "deployment"})

    deploy_resp = httpx.post(
        f"{settings.databricks_host}/api/2.0/apps/{app_name}/deployments",
        json={"source_code_path": workspace_path},
        headers=headers,
        timeout=30.0,
    )

    if deploy_resp.status_code not in (200, 201):
        return {"error": f"Deployment failed: {deploy_resp.text[:200]}", "current_step": "deployment"}

    deployment_id = deploy_resp.json().get("deployment_id", "")
    logger.info(f"Deployment created: {deployment_id}", extra={"step": "deployment"})

    # ─── Step 6: Wait for deployment + check health ──────────────────
    logger.info("Waiting for deployment to complete...", extra={"step": "deployment"})
    deploy_status, deploy_message = _wait_for_deployment(
        settings.databricks_host, token, app_name, deployment_id, timeout=180
    )

    if deploy_status == "FAILED":
        # Fetch error logs for self-healing
        error_logs = _get_app_logs(settings.databricks_host, token, app_name, app_url)
        logger.error(f"Deployment failed. Logs: {error_logs[:500]}", extra={"step": "deployment"})

        # If we haven't exceeded retry limit, return error context for self-healing
        if retry_count < MAX_DEPLOYMENT_RETRIES:
            return {
                "deployment_error_logs": error_logs,
                "deployment_retry_count": retry_count + 1,
                "deployment_fix_context": _build_fix_context(error_logs, bundle_files),
                "current_step": "deployment",
                "error": "",  # Clear error so pipeline can retry
            }
        else:
            return {
                "error": f"App crashed after {MAX_DEPLOYMENT_RETRIES} retries. Logs: {error_logs[:300]}",
                "current_step": "deployment",
            }

    # ─── Step 7: Grant SP permissions ────────────────────────────────
    if sp_client_id:
        try:
            repo = _get_repo()
            repo.grant_schema_access(schema_name, sp_client_id)
            logger.info(f"Granted schema access to SP: {sp_client_id}", extra={"step": "deployment"})
        except Exception as e:
            logger.warning(f"Permission grant failed (non-fatal): {e}")

    # Get final URL
    if not app_url or app_url == "Unavailable":
        app_resp = httpx.get(f"{settings.databricks_host}/api/2.0/apps/{app_name}", headers=headers, timeout=15.0)
        if app_resp.status_code == 200:
            app_url = app_resp.json().get("url", f"{settings.databricks_host}/apps/{app_name}")

    logger.info(f"Deployment complete: {app_url}", extra={"step": "deployment"})

    return {
        "app_url": app_url,
        "service_principal_id": sp_client_id,
        "deployment_tested": True,
        "deployment_error_logs": "",
        "deployment_retry_count": retry_count,
        "current_step": "deployment",
        "completed_steps": state.get("completed_steps", []) + ["deployment"],
    }


